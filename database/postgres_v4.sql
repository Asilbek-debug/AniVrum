CREATE TABLE animes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    title TEXT NOT NULL,
    genre TEXT,
    description TEXT,
    release_year BIGINT,
    kind TEXT NOT NULL DEFAULT 'anime' CHECK (kind IN ('anime', 'movie')),
    poster_file_id TEXT,
    visible BIGINT NOT NULL DEFAULT 1,
    created_at TEXT,
    movie_file_id TEXT,
    movie_media_type TEXT,
    country TEXT,
    caption_mode TEXT NOT NULL DEFAULT 'auto',
    caption_text TEXT,
    caption_link TEXT
);

-- SQLite keeps historical references even when the corresponding content is deleted.
CREATE TABLE seasons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anime_id BIGINT NOT NULL,
    season_number BIGINT NOT NULL,
    UNIQUE (anime_id, season_number)
);
CREATE TABLE episodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL,
    episode_number BIGINT NOT NULL,
    title TEXT,
    video_file_id TEXT,
    media_type TEXT NOT NULL DEFAULT 'video',
    file_unique_id TEXT,
    UNIQUE (season_id, episode_number)
);
CREATE UNIQUE INDEX idx_episode_file ON episodes (season_id, file_unique_id)
    WHERE file_unique_id IS NOT NULL;

CREATE TABLE favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    anime_id BIGINT NOT NULL,
    UNIQUE (user_id, anime_id)
);
CREATE TABLE anime_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anime_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    episode_id BIGINT NOT NULL,
    viewed_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    season_id BIGINT
);
CREATE INDEX idx_views_anime ON anime_views (anime_id);
CREATE INDEX idx_views_time ON anime_views (viewed_at);
CREATE INDEX idx_views_season ON anime_views (season_id);
CREATE INDEX idx_catalog ON animes (visible, kind,
    (translate(title, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz') COLLATE "C"));

CREATE TABLE announcements (
    anime_id BIGINT PRIMARY KEY,
    status TEXT NOT NULL,
    chat_id TEXT,
    message_id BIGINT,
    poster_file_id TEXT,
    is_text BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE content_codes (
    code TEXT PRIMARY KEY,
    anime_id BIGINT NOT NULL
);
CREATE TABLE standalone_videos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anime_id BIGINT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('film', 'ova')),
    number BIGINT NOT NULL CHECK (number > 0),
    title TEXT NOT NULL,
    description TEXT,
    file_id TEXT NOT NULL,
    media_type TEXT NOT NULL,
    release_year BIGINT,
    country TEXT,
    genre TEXT,
    UNIQUE (anime_id, kind, number)
);
CREATE TABLE anime_news (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anime_id BIGINT,
    kind TEXT NOT NULL CHECK (kind IN ('anime', 'film', 'ova', 'general')),
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    photo TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    published_at TEXT
);
CREATE TABLE anime_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anime_id BIGINT,
    anime_title TEXT NOT NULL,
    anime_code TEXT NOT NULL,
    user_id BIGINT NOT NULL,
    name TEXT NOT NULL,
    username TEXT,
    body TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX idx_comment_user_time ON anime_comments (user_id, created_at);
CREATE TABLE bot_users (
    user_id BIGINT PRIMARY KEY,
    last_active TEXT NOT NULL
);
CREATE TABLE bot_metrics (
    day TEXT NOT NULL,
    kind TEXT NOT NULL,
    subject BIGINT NOT NULL,
    total BIGINT NOT NULL,
    PRIMARY KEY (day, kind, subject)
);
